<?php

namespace App\Http\Controllers\Files;

use App\Enums\FileType;
use App\Http\Controllers\Controller;
use App\Models\StoredFile;
use Illuminate\Filesystem\FilesystemAdapter;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Storage;
use Symfony\Component\HttpFoundation\Response;

/**
 * Download of a stored file (D-218): the permission is checked by the route (StoredFilePolicy),
 * the file is read from the private disk and never served directly by the web server.
 *
 * - Content-Type is the type verified when the file was stored, with nosniff so the browser never
 *   guesses another one.
 * - Images and PDFs open in the browser (previews, PDF viewer), Excel files are saved.
 * - Images and Excel files also get a CSP sandbox: even a file opened in a tab cannot run
 *   anything. Not the PDFs, generated by the portal: Chrome refuses to show a PDF in a sandbox.
 * - Cache: private, revalidated at every request with the SHA-256 as ETag. Files never change, so
 *   an unchanged file costs a "304 Not Modified", and a revoked permission applies at once.
 */
final class StoredFileDownloadController extends Controller
{
    public function __invoke(Request $request, StoredFile $storedFile): Response
    {
        $type = $storedFile->type();
        $headers = [
            'Content-Type' => $type->mimeType(),
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'private, no-cache',
            'ETag' => '"'.$storedFile->sha256.'"',
        ];

        if ($type !== FileType::Pdf) {
            $headers['Content-Security-Policy'] = "default-src 'none'; sandbox";
        }

        if (in_array($headers['ETag'], $request->getETags(), true)) {
            return response('', Response::HTTP_NOT_MODIFIED, array_diff_key($headers, ['Content-Type' => true]));
        }

        /** @var FilesystemAdapter $disk */
        $disk = Storage::disk($storedFile->disk);

        if (! $disk->exists($storedFile->path)) {
            Log::warning('Stored file missing on the private disk.', ['stored_file_id' => $storedFile->id]);
            abort(Response::HTTP_NOT_FOUND);
        }

        return $disk->response($storedFile->path, $storedFile->downloadName(), $headers, $type->disposition());
    }
}
