<?php

namespace App\Domain\Files\Services;

use App\Domain\Files\Data\InspectedFile;
use App\Domain\Files\Exceptions\InvalidFile;
use App\Enums\FilePurpose;
use App\Enums\FileType;
use finfo;
use Illuminate\Support\Facades\File;
use ZipArchive;

/**
 * Checks a file content against the rules of its purpose (D-218, C10), before anything is stored.
 *
 * - The type comes from the content (libmagic via ext-fileinfo), never from the extension or the
 *   type declared by the browser. SVG, HTML, PHP and every type not listed for the purpose are
 *   refused.
 * - Images: decoded header (getimagesize) consistent with the type; size in pixels checked before
 *   any decoding, so a small file cannot ask for hundreds of megabytes; JPEG in CMYK refused,
 *   because GD would alter its colours when re-encoding.
 * - Excel: only the container of an .xlsx workbook without macros (D-218). The cells are read by
 *   the calendar import of slice F1.
 * - PDF: generated by the portal (M09), only recognised as PDF.
 *
 * Every refusal is an InvalidFile with the Italian message for the user.
 */
final class FileInspector
{
    /** Largest Excel accepted once unpacked, and number of parts (protection from zip bombs). */
    private const XLSX_MAX_UNPACKED_BYTES = 100 * 1024 * 1024;

    private const XLSX_MAX_ENTRIES = 10_000;

    public function inspect(string $contents, FilePurpose $purpose): InspectedFile
    {
        $bytes = strlen($contents);

        if ($bytes === 0) {
            throw InvalidFile::empty();
        }

        $maxBytes = $purpose->maxBytes();
        if ($maxBytes !== null && $bytes > $maxBytes) {
            throw InvalidFile::tooLarge($bytes, $maxBytes);
        }

        $type = $this->detectType($contents);

        if ($type === null || ! in_array($type, $purpose->allowedTypes(), true)) {
            throw InvalidFile::typeNotAllowed(array_map(
                fn (FileType $allowed): string => $allowed->label(),
                $purpose->allowedTypes(),
            ));
        }

        return match ($type) {
            FileType::Png, FileType::Jpeg => $this->inspectImage($contents, $type, $purpose),
            FileType::Xlsx => $this->inspectWorkbook($contents),
            FileType::Pdf => new InspectedFile(FileType::Pdf),
        };
    }

    /**
     * Type from the content. An .xlsm or a generic ZIP counts as a workbook candidate: the check
     * of the container then explains what is wrong (macros, not a workbook).
     */
    private function detectType(string $contents): ?FileType
    {
        $mimeType = strtolower((string) (new finfo(FILEINFO_MIME_TYPE))->buffer($contents));

        return match (true) {
            $mimeType === 'image/png' => FileType::Png,
            $mimeType === 'image/jpeg' => FileType::Jpeg,
            $mimeType === 'application/pdf' && str_starts_with($contents, '%PDF-') => FileType::Pdf,
            $mimeType === 'application/zip',
            str_starts_with($mimeType, 'application/vnd.openxmlformats-officedocument.spreadsheetml.'),
            str_starts_with($mimeType, 'application/vnd.ms-excel.sheet.macroenabled') => FileType::Xlsx,
            default => null,
        };
    }

    private function inspectImage(string $contents, FileType $type, FilePurpose $purpose): InspectedFile
    {
        $info = @getimagesizefromstring($contents);
        $expected = $type === FileType::Png ? IMAGETYPE_PNG : IMAGETYPE_JPEG;

        if ($info === false || $info[2] !== $expected || $info[0] < 1 || $info[1] < 1) {
            throw InvalidFile::unreadable();
        }

        [$width, $height] = [$info[0], $info[1]];

        if ($type === FileType::Jpeg && ($info['channels'] ?? 3) === 4) {
            throw InvalidFile::cmyk();
        }

        $exact = $purpose->exactDimensions();
        if ($exact !== null && ($width !== $exact[0] || $height !== $exact[1])) {
            throw InvalidFile::wrongDimensions($width, $height, $exact[0], $exact[1]);
        }

        $maxSide = $purpose->maxSide();
        if ($maxSide !== null && max($width, $height) > $maxSide) {
            throw InvalidFile::tooManyPixels($width, $height, $maxSide);
        }

        return new InspectedFile($type, $width, $height);
    }

    /**
     * An .xlsx is a ZIP with the parts of a workbook. Refused: macros (vbaProject.bin or a
     * macro-enabled content type, i.e. .xlsm), templates and other OOXML files, old .xls files
     * (not a ZIP), archives too big once unpacked.
     */
    private function inspectWorkbook(string $contents): InspectedFile
    {
        $path = tempnam(sys_get_temp_dir(), 'xlsx');
        if ($path === false) {
            throw InvalidFile::unreadable();
        }

        try {
            File::put($path, $contents);
            $zip = new ZipArchive;

            if ($zip->open($path, ZipArchive::RDONLY | ZipArchive::CHECKCONS) !== true) {
                throw InvalidFile::notXlsx();
            }

            try {
                $this->checkWorkbookParts($zip);
            } finally {
                $zip->close();
            }
        } finally {
            File::delete($path);
        }

        return new InspectedFile(FileType::Xlsx);
    }

    private function checkWorkbookParts(ZipArchive $zip): void
    {
        if ($zip->numFiles > self::XLSX_MAX_ENTRIES) {
            throw InvalidFile::tooLargeUnpacked();
        }

        $unpacked = 0;
        $names = [];

        for ($index = 0; $index < $zip->numFiles; $index++) {
            $stat = $zip->statIndex($index);
            if ($stat === false) {
                throw InvalidFile::notXlsx();
            }

            $unpacked += $stat['size'];
            $names[] = strtolower($stat['name']);
        }

        if ($unpacked > self::XLSX_MAX_UNPACKED_BYTES) {
            throw InvalidFile::tooLargeUnpacked();
        }

        foreach ($names as $name) {
            if (str_ends_with($name, 'vbaproject.bin')) {
                throw InvalidFile::macros();
            }
        }

        if (! in_array('[content_types].xml', $names, true) || ! in_array('xl/workbook.xml', $names, true)) {
            throw InvalidFile::notXlsx();
        }

        $contentTypes = strtolower((string) $zip->getFromName('[Content_Types].xml', 1024 * 1024, ZipArchive::FL_NOCASE));

        if (str_contains($contentTypes, 'macroenabled')) {
            throw InvalidFile::macros();
        }

        if (! str_contains($contentTypes, 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml')) {
            throw InvalidFile::notXlsx();
        }
    }
}
