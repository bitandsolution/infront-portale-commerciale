<?php

namespace App\Enums;

use App\Support\Text;

/**
 * What a stored file is for (C10), saved in stored_files.purpose (C8). Each purpose carries the
 * rules checked on the content before the file is stored (D-218):
 *
 * - client logo: PNG or JPG up to 2 MB (M05 §6, M05-CA4);
 * - club logo: same rules as the client logo (M02 F-05, D-230);
 * - slide image: PNG only, exactly 1920×1080, up to 10 MB (M08 §7, M08-CA8);
 * - calendar import: Excel .xlsx without macros, up to 5 MB (M02 F-09); cells are read in slice F1;
 * - generated PDF: produced by the portal itself (M09), only checked to be a PDF.
 *
 * Logos accept at most 5000 pixels per side: beyond that a small file could ask for hundreds of
 * megabytes once decoded.
 *
 * Who may download a file depends on the purpose: App\Policies\StoredFilePolicy.
 */
enum FilePurpose: string
{
    case ClientLogo = 'client_logo';
    case ClubLogo = 'club_logo';
    case SlideImage = 'slide_image';
    case CalendarImport = 'calendar_import';
    case GeneratedPdf = 'generated_pdf';

    private const MEGABYTE = 1024 * 1024;

    /**
     * @return list<FileType>
     */
    public function allowedTypes(): array
    {
        return match ($this) {
            self::ClientLogo, self::ClubLogo => [FileType::Png, FileType::Jpeg],
            self::SlideImage => [FileType::Png],
            self::CalendarImport => [FileType::Xlsx],
            self::GeneratedPdf => [FileType::Pdf],
        };
    }

    /**
     * Largest accepted file in bytes; null for the PDFs generated by the portal (M09 §9 only warns
     * beyond 20 MB, it never refuses).
     */
    public function maxBytes(): ?int
    {
        return match ($this) {
            self::ClientLogo, self::ClubLogo => 2 * self::MEGABYTE,
            self::SlideImage => 10 * self::MEGABYTE,
            self::CalendarImport => 5 * self::MEGABYTE,
            self::GeneratedPdf => null,
        };
    }

    /**
     * Width and height the image must have exactly, if any.
     *
     * @return array{int, int}|null
     */
    public function exactDimensions(): ?array
    {
        return $this === self::SlideImage ? [1920, 1080] : null;
    }

    /**
     * Longest accepted side of an image in pixels, if any.
     */
    public function maxSide(): ?int
    {
        return match ($this) {
            self::ClientLogo, self::ClubLogo => 5000,
            default => null,
        };
    }

    /**
     * Italian name for the messages and the server commands (lang/it/files.php).
     */
    public function label(): string
    {
        return Text::get('files.purposes.'.$this->value);
    }
}
