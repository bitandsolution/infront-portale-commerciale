namespace App\Support\Files;

use GdImage;
use RuntimeException;
use ZipArchive;

/**
 * Synthetic files for the tests and the development command files:try (PR-06): images drawn
 * with GD, minimal Excel and PDF files, disguised files. No real file is kept in the repository.
 */
final class SampleFiles
{
    /**
     * PNG drawn with GD; with a text, a tEXt chunk is added after the header, as image editors do.
     */
    public static function png(int $width, int $height, ?string $text = null): string
    {
        $png = self::encode(self::canvas($width, $height), 'png');

        if ($text === null) {
            return $png;
        }

        // Signature (8 bytes) + IHDR chunk (25 bytes), then the new chunk.
        $data = "Comment\0".$text;
        $chunk = pack('N', strlen($data)).'tEXt'.$data.pack('N', crc32('tEXt'.$data));

        return substr($png, 0, 33).$chunk.substr($png, 33);
    }

    /**
     * JPEG drawn with GD; with $exif an APP1 "Exif" segment is added after the start marker.
     */
    public static function jpeg(int $width, int $height, bool $exif = false): string
    {
        $jpeg = self::encode(self::canvas($width, $height), 'jpeg');

        if (! $exif) {
            return $jpeg;
        }

        // TIFF header (little endian) with one IFD of zero entries, plus a readable marker.
        $payload = "Exif\0\0"."II*\0".pack('V', 8)."\0\0".pack('V', 0).'Test camera';

        return substr($jpeg, 0, 2)."\xFF\xE1".pack('n', strlen($payload) + 2).$payload.substr($jpeg, 2);
    }

