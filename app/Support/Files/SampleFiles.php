    /**
     * Minimal .xlsx container: the parts the inspector looks for. With $macros it becomes an .xlsm
     * (macro-enabled content type and a vbaProject.bin part).
     */
    public static function xlsx(bool $macros = false): string
    {
        $workbookType = $macros
            ? 'application/vnd.ms-excel.sheet.macroEnabled.main+xml'
            : 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml';

        $parts = [
            '[Content_Types].xml' => '<?xml version="1.0" encoding="UTF-8"?>'
                .'<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                .'<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                .'<Default Extension="xml" ContentType="application/xml"/>'
                .'<Override PartName="/xl/workbook.xml" ContentType="'.$workbookType.'"/>'
                .'</Types>',
            '_rels/.rels' => '<?xml version="1.0" encoding="UTF-8"?>'
                .'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                .'<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
                .'</Relationships>',
            'xl/workbook.xml' => '<?xml version="1.0" encoding="UTF-8"?>'
                .'<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheets/></workbook>',
        ];

        if ($macros) {
            $parts['xl/vbaProject.bin'] = 'test macro';
        }

        return self::zip($parts);
    }

    /**
     * Start of an old Excel .xls file (OLE compound document signature).
     */
    public static function xls(): string
    {
        return "\xD0\xCF\x11\xE0\xA1\xB1\x1A\xE1".str_repeat("\0", 504);
    }

    /**
     * Minimal one-page PDF, as a document generated by the portal.
     */
    public static function pdf(): string
    {
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 1920 1080] >>',
        ];

        $pdf = "%PDF-1.7\n";
        $offsets = [];
        foreach ($objects as $index => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($index + 1)." 0 obj\n{$object}\nendobj\n";
        }

        $xref = strlen($pdf);
        $pdf .= "xref\n0 ".(count($objects) + 1)."\n0000000000 65535 f \n";
        foreach ($offsets as $offset) {
            $pdf .= sprintf("%010d 00000 n \n", $offset);
        }

        return $pdf.'trailer << /Size '.(count($objects) + 1)." /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF\n";
    }

    public static function php(): string
    {
        return "<?php\nsystem(\$_GET['cmd'] ?? 'id');\n";
    }

    public static function html(): string
    {
        return "<!DOCTYPE html>\n<html><body><script>alert('prova')</script></body></html>\n";
    }

    public static function svg(): string
    {
        return '<?xml version="1.0" encoding="UTF-8"?>'."\n"
            .'<svg xmlns="http://www.w3.org/2000/svg" width="300" height="100"><script>alert(1)</script>'
            .'<rect width="300" height="100" fill="#C8102E"/></svg>'."\n";
    }

    /**
     * Same content followed by junk up to $bytes: a file of that weight that is still recognised
     * by its type.
     */
    public static function padded(string $contents, int $bytes): string
    {
        return $contents.str_repeat("\0", max(0, $bytes - strlen($contents)));
    }

    private static function canvas(int $width, int $height): GdImage
    {
        $image = imagecreatetruecolor($width, $height);
        if ($image === false) {
            throw new RuntimeException('GD cannot create the sample image.');
        }

        imagefill($image, 0, 0, (int) imagecolorallocate($image, 200, 16, 46));
        imagefilledrectangle($image, intdiv($width, 4), intdiv($height, 4), intdiv($width * 3, 4), intdiv($height * 3, 4), (int) imagecolorallocate($image, 255, 255, 255));

        return $image;
    }

    private static function encode(GdImage $image, string $format): string
    {
        ob_start();
        $format === 'png' ? imagepng($image) : imagejpeg($image, null, 80);

        return (string) ob_get_clean();
    }

    /**
     * @param  array<string, string>  $parts
     */
    private static function zip(array $parts): string
    {
        $path = (string) tempnam(sys_get_temp_dir(), 'zip');
        $zip = new ZipArchive;
        $zip->open($path, ZipArchive::OVERWRITE);
        foreach ($parts as $name => $contents) {
            $zip->addFromString($name, $contents);
        }
        $zip->close();

        // Plain PHP instead of the File facade: the tests build samples while the datasets load.
        $contents = (string) file_get_contents($path);
        unlink($path);

        return $contents;
    }
}
